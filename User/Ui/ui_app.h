#ifndef __UI_APP_H
#define __UI_APP_H

#include "stm32f10x.h"
#include <stdint.h>

/**
  * @brief  初始化本地界面（LCD + 触摸 + 清屏 + 画首帧）
  * @note   内部会调用 uip_init()，即 LCD_Init()/TP_Init()，
  *         所以 main() 里不需要再单独初始化 LCD。
  *         LCD 初始化约 100~300 ms，放在所有外设初始化之后调用即可。
  */
void UI_Init(void);

/**
  * @brief  界面周期任务（在主循环中尽可能频繁地调用）
  * @note   函数内部依据毫秒时间自己掌握节奏：
  *           · 触摸每 30 ms 扫描一次
  *           · 主界面每 500 ms 重绘一次
  *           · 历史界面每 1000 ms 重绘一次
  *         因此主循环里直接无脑调用即可，不会拖慢 CAN 实时链路。
  */
void UI_Tick(void);

/**
  * @brief  界面毫秒时基（在 SysTick 中断里每 1 ms 调用一次）
  * @note   只做一次加法，开销可忽略。所有绘图都在 UI_Tick() 里完成，
  *         中断里绝不碰 LCD —— 这是保证 CAN 实时性的一条硬规矩。
  *         调用位置：stm32f10x_it.c 的 SysTick_Handler()。
  */
void UI_Tick_1ms(void);

/** 当前是否停在历史曲线界面（1 = 是） */
uint8_t UI_IsCurveScreen(void);

/** 清空历史采样（开始新一次充电会话时调用） */
void UI_ClearHistory(void);

#endif /* __UI_APP_H */
