/**
  ******************************************************************************
  * @file    ctiic.h
  * @brief   电容触摸屏专用软件 I2C（bit-banging）
  *
  * 为什么不用硬件 I2C
  * ------------------
  *   STM32F103 的硬件 I2C 有众所周知的各种坑（总线锁死、需要反复复位），
  *   而触摸屏的数据量极小（一次读十几个字节），软件 I2C 完全够用，
  *   而且引脚随便挪、出问题一眼能看出来。正点原子官方例程也是这么做的。
  *
  * 引脚为什么做成"可配置"
  * ----------------------
  *   不同批次的触摸模块，I2C 接的引脚不一样（常见 PB6/PB7、PB0/PB1、
  *   PC0/PC1…），而这一点光看代码是看不出来的。
  *   所以这里把引脚做成运行时可切换的：touch.c 会在初始化时依次在几组
  *   候选引脚上探测触摸芯片，哪组有应答就用哪组，并把结果打印到串口。
  *   这样既不用猜，也能在日志里一眼看到实际用的是哪组引脚。
  *
  * 电气实现
  * --------
  *   输出时用「推挽输出」（和正点原子例程一致），输入时切「上拉输入」。
  *   之所以不用开漏：不少模块的排线上并没有外部上拉电阻，
  *   开漏输出在没有上拉的情况下根本拉不高，总线永远是死的。
  *   推挽 + 每次等待都带超时保护，是这块板子上最稳的做法。
  ******************************************************************************
  */

#ifndef __CTIIC_H
#define __CTIIC_H

#include "stm32f10x.h"
#include <stddef.h>

/*==============================================================================
 *                              引脚配置
 *============================================================================*/
typedef struct
{
    GPIO_TypeDef *scl_port;
    uint16_t      scl_pin;
    GPIO_TypeDef *sda_port;
    uint16_t      sda_pin;
    const char   *name;         /* 日志里显示用，例如 "PB6/PB7" */
} ct_iic_pins_t;

/** 切换引脚组（会重新初始化这两个引脚为 GPIO）；传 NULL 恢复默认 */
void CT_IIC_SetPins(const ct_iic_pins_t *pins);

/** 取当前引脚组 */
const ct_iic_pins_t *CT_IIC_GetPins(void);

/** 按当前引脚组初始化 GPIO */
void CT_IIC_Init(void);

/** 释放总线（把 SCL/SDA 都拉高） */
void CT_IIC_Release(void);

/*==============================================================================
 *                              基本读写
 *   返回值：0 = 从机有应答（成功）；1 = 无应答 / 总线异常
 *============================================================================*/

/** 8 位寄存器地址 + 单字节写（FT 系列用） */
uint8_t CT_IIC_WriteReg8(uint8_t dev, uint8_t reg, uint8_t data);

/** 8 位寄存器地址 + 连续读（FT 系列用） */
uint8_t CT_IIC_ReadReg8(uint8_t dev, uint8_t reg, uint8_t *buf, uint16_t len);

/** 16 位寄存器地址 + 单字节写（GT9147 / GT1151 用） */
uint8_t CT_IIC_WriteReg16(uint8_t dev, uint16_t reg, uint8_t data);

/** 16 位寄存器地址 + 连续读（GT9147 / GT1151 用） */
uint8_t CT_IIC_ReadReg16(uint8_t dev, uint16_t reg, uint8_t *buf, uint16_t len);

/** 探针：只发一个起始条件 + 设备地址，看有没有应答（不改动从机状态） */
uint8_t CT_IIC_Probe(uint8_t dev);

#endif /* __CTIIC_H */
