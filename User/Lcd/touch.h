/**
  ******************************************************************************
  * @file    touch.h
  * @brief   电容触摸驱动（GT9147 / GT1151 / FT5206 / FT5426 自动识别）
  *
  * 对外接口与正点原子例程保持一致（tp_dev.scan() / tp_dev.x[] / tp_dev.y[]），
  * 所以 User/Ui/ui_port.c 那边不需要为触摸写任何特例代码。
  ******************************************************************************
  */

#ifndef __TOUCH_H
#define __TOUCH_H

#include "stm32f10x.h"

/*==============================================================================
 *                              状态标志
 *============================================================================*/
#define TP_PRES_DOWN    0x80        /* 当前有手指按下 */

/*==============================================================================
 *                              坐标处理开关
 *
 *   触摸芯片上报的是「面板坐标系」，横竖屏切换、模块装反都会导致
 *   坐标与显示对不上。这里给三个开关，按实际现象调整：
 *     现象：左右反了 → TP_MIRROR_X 置 1
 *     现象：上下反了 → TP_MIRROR_Y 置 1
 *     现象：X/Y 互换（横向拖动竖着动）→ TP_SWAP_XY 置 1
 *   改完重新编译烧录即可，不用改任何逻辑代码。
 *============================================================================*/
#define TP_SWAP_XY      0
#define TP_MIRROR_X     0
#define TP_MIRROR_Y     0

/* 是否自动在几组候选引脚上探测触摸芯片（推荐开着，探测结果会打到串口） */
#define TP_AUTO_PROBE   1

/* 已知触摸芯片类型 */
typedef enum
{
    TP_CHIP_NONE = 0,
    TP_CHIP_GT,             /* GT9147 / GT1151 / GT911 …（16 位寄存器地址） */
    TP_CHIP_FT,             /* FT5206 / FT5426 / FT6236 …（8 位寄存器地址）  */
    TP_CHIP_UNKNOWN         /* 有器件应答但认不出型号 */
} tp_chip_t;

/*==============================================================================
 *                              设备结构（与正点原子同名，便于对照）
 *============================================================================*/
typedef struct
{
    uint8_t  (*init)(void);         /* 初始化函数指针 */
    uint8_t  (*scan)(uint8_t);      /* 扫描函数指针 */
    uint16_t x[5];                  /* 最多 5 点触摸的坐标 */
    uint16_t y[5];
    uint8_t  sta;                   /* 状态：bit7 = TP_PRES_DOWN */
} _m_tp_dev;

extern _m_tp_dev tp_dev;

/*==============================================================================
 *                              接口
 *============================================================================*/

/**
  * @brief  初始化触摸屏
  * @note   会自动在候选 I2C 引脚上探测触摸芯片，并把结果打印到串口。
  *         探测失败不致命：tp_dev.scan 仍然可用，只是永远返回"未按下"，
  *         界面照常显示，只是不能触摸切页。
  */
void TP_Init(void);

/** 扫描函数（tp_dev.scan 指向它）；mode 固定传 0（屏幕坐标） */
uint8_t TP_Scan(uint8_t mode);

/** 识别到的触摸芯片类型 / 名称（诊断用） */
tp_chip_t   TP_GetChip(void);
const char *TP_GetChipName(void);

/** 触摸是否可用（1 = 识别到芯片） */
uint8_t TP_IsReady(void);

#endif /* __TOUCH_H */
