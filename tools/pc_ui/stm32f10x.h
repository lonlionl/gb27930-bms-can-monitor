/**
 * tools/pc_ui/stm32f10x.h  --  DEV-ONLY STUB, NOT PART OF THE DELIVERY
 *
 * ui_port.h includes "stm32f10x.h". When we compile the STM32 UI on a PC
 * (to render its layout as ASCII art and eyeball it), we do not want the
 * real CMSIS header. This stub only provides the handful of type aliases
 * that the UI sources actually use.
 */

#ifndef __STM32F10X_H
#define __STM32F10X_H

#include <stdint.h>

typedef uint8_t  u8;
typedef uint16_t u16;
typedef uint32_t u32;
typedef int8_t   s8;
typedef int16_t  s16;
typedef int32_t  s32;

#endif /* __STM32F10X_H */
